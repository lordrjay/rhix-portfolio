function addMsg(who,text){ const d=document.createElement('div'); d.className='msg '+who; d.textContent=text; chatFull.appendChild(d); chatFull.scrollTop=9999; }
function sparkReply(q){
  q=q.toLowerCase();
  if(q.includes('verif')||q.includes('test')) return 'I verify everything: I run the code, add tests, and show you logs + before/after. No “trust me” — only evidence. Try the Terminal tab → “spark test --coverage”.';
  if(q.includes('stack')||q.includes('build')) return 'My go-to: React + TypeScript frontend, Python/FastAPI or Node backend, Fabric/Postgres data, Azure + Docker deploy. But I adapt to YOUR repo in seconds.';
  if(q.includes('price')||q.includes('cost')) return 'This demo is free and runs fully client-side. For real projects, just describe the outcome — I’ll scope it into a tight plan first.';
  if(q.includes('who')||q.includes('you')) return 'I’m Muse Spark 1.3, running in opencode — an AI engineer that reasons, builds, runs, and verifies. Think pair-programmer with infinite stamina. ✦';
  if(q.includes('data')||q.includes('fabric')||q.includes('power bi')) return 'Love data. I do medallion lakehouses, DAX tuning, KQL real-time, and Power BI design. Check the Data Pulse tab for a live taste 📊';
  return 'Great question. In a real session I’d inspect your files, propose a 3-step plan, implement it, then run verification. Give me a repo + goal and watch me cook. ⚡';
}
