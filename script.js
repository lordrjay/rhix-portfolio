/* Particles */
(() => {
  const c = $('#particles'), x = c.getContext('2d');
  let W, H, pts = [];
  const resize = () => { W = c.width = innerWidth; H = c.height = innerHeight; };
  resize(); addEventListener('resize', resize);
  for (let i = 0; i < 90; i++) pts.push({ x: Math.random()*innerWidth, y: Math.random()*innerHeight, vx:(Math.random()-.5)*.4, vy:(Math.random()-.5)*.4, r:Math.random()*2+.4, h:Math.random()>.5?'124,92,255':'0,229,255' });
  (function loop(){
    x.clearRect(0,0,W,H);
    pts.forEach(p=>{ p.x+=p.vx; p.y+=p.vy; if(p.x<0||p.x>W)p.vx*=-1; if(p.y<0||p.y>H)p.vy*=-1;
      x.beginPath(); x.arc(p.x,p.y,p.r,0,7); x.fillStyle=`rgba(${p.h},.7)`; x.fill(); });
    // links
    for(let i=0;i<pts.length;i++) for(let j=i+1;j<pts.length;j++){
      const dx=pts[i].x-pts[j].x, dy=pts[i].y-pts[j].y, d=Math.hypot(dx,dy);
      if(d<130){ x.strokeStyle=`rgba(124,92,255,${(1-d/130)*.25})`; x.beginPath(); x.moveTo(pts[i].x,pts[i].y); x.lineTo(pts[j].x,pts[j].y); x.stroke(); }
    }
    requestAnimationFrame(loop);
  })();
})();

