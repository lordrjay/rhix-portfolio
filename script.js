let chartData = [];
function genData(mode){
  const n=28; chartData=[];
  for(let i=0;i<n;i++){
    let v;
    if(mode==='growth') v=20+i*2.6+Math.random()*14;
    else if(mode==='spike') v=22+Math.random()*10+(i>17&&i<23?70*Math.sin((i-17)/5*Math.PI):0);
    else v=50+Math.sin(i/3)*22+Math.random()*8;
    chartData.push(v);
  }
  const sum=chartData.reduce((a,b)=>a+b,0);
  $('#kpi1').textContent='$'+(sum/28*1.7/1000).toFixed(1)+'k';
  $('#kpi2').textContent=Math.round(sum*42).toLocaleString();
  $('#kpi3').textContent=(1+Math.random()*2).toFixed(1)+'%';
  $('#dataInsight').textContent = mode==='spike' ? 'Insight: viral spike detected days 18–22 — 3.1× baseline. Spark suggests: scale edge cache + trigger win-back flow.' : mode==='growth' ? 'Insight: steady compounding growth (+9.4% WoW). Spark suggests: raise Pro price test + ship referral loop.' : 'Insight: healthy weekly seasonality. Spark suggests: schedule deploys in troughs, promos at peaks.';
  drawChart();
}
function drawChart(){
  const c=$('#chart'), ctx=c.getContext('2d');
  const dpr=devicePixelRatio||1, w=c.clientWidth||600, h=220;
  c.width=w*dpr; c.height=h*dpr; ctx.scale(dpr,dpr);
  ctx.clearRect(0,0,w,h);
  const max=Math.max(...chartData)*1.15, min=Math.min(...chartData)*.85;
  const px=i=>20+i*(w-40)/(chartData.length-1), py=v=>h-24-((v-min)/(max-min))*(h-60);
  // grid
  ctx.strokeStyle='rgba(150,160,220,.15)'; for(let g=0;g<4;g++){const y=20+g*(h-60)/3; ctx.beginPath(); ctx.moveTo(20,y); ctx.lineTo(w-16,y); ctx.stroke();}
  const grad=ctx.createLinearGradient(0,0,w,0); grad.addColorStop(0,'#7c5cff'); grad.addColorStop(.5,'#00e5ff'); grad.addColorStop(1,'#ff4ecd');
  ctx.beginPath(); chartData.forEach((v,i)=>i?ctx.lineTo(px(i),py(v)):ctx.moveTo(px(i),py(v)));
  ctx.strokeStyle=grad; ctx.lineWidth=3; ctx.lineJoin='round'; ctx.stroke();
  ctx.lineTo(px(chartData.length-1),h-20); ctx.lineTo(px(0),h-20); ctx.closePath();
  const fg=ctx.createLinearGradient(0,0,0,h); fg.addColorStop(0,'rgba(0,229,255,.3)'); fg.addColorStop(1,'rgba(124,92,255,0)'); ctx.fillStyle=fg; ctx.fill();
  // dots
  ctx.fillStyle='#fff'; chartData.forEach((v,i)=>{ if(i%4===0){ctx.beginPath(); ctx.arc(px(i),py(v),3.4,0,7); ctx.fill();} });
}
